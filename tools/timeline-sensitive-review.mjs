/**
 * The human-review record for every sensitive timeline record (5.0 §5.3, §5.9).
 *
 * §5.3 ends "joins the human-review launch gates", and §5.9 makes those gates
 * explicit: pediatric/developmental review of every child-development and puberty
 * record, clinical review of every fertility, health-decline and dying record and
 * of the later-life intro's life-expectancy paragraph.
 *
 * This generates the document those reviewers actually read: every sensitive record
 * in full, with its care note, its routes, the exact source sentence behind any
 * figure, and the specific question each reviewer is being asked. It is generated
 * rather than written so it cannot fall behind the content.
 *
 * Usage: node --experimental-strip-types tools/timeline-sensitive-review.mjs
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { MILESTONES, SOURCES } from "../content/timeline/generated/index.ts";
import { LANE_LABEL, KIND_LABEL, SCREENING_LINE, VARIATION_LINE } from "../content/timeline/schema.ts";
import { windowText } from "../content/timeline/select.ts";
import { STAGES_TL } from "../content/timeline/stages.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const REVIEWER = {
  "child-development": "PEDIATRIC / DEVELOPMENTAL",
  puberty: "PEDIATRIC / DEVELOPMENTAL",
  fertility: "CLINICAL",
  "health-decline": "CLINICAL",
  dying: "CLINICAL",
};

const ASK = {
  "child-development":
    "Does anything here read as a screening threshold, a test, or a verdict on one child? Is the population framing the source's own? Would a worried parent be pointed at a clinician rather than reassured or alarmed by this page?",
  puberty:
    "Is this stated in a way a young person reading it about their own body would find matter-of-fact rather than measuring? Is the range wide enough, and stated as a range?",
  fertility:
    "A window narrowing is stated as a sourced fact. Does any sentence turn it into a deadline, a penalty, or a verdict on a body? Are the alternatives rendered as routes rather than consolation, and are they unranked? Would a person who wanted children and did not have them find anything here that reads as judgement?",
  "health-decline":
    "Is this matter-of-fact rather than either dread or false reassurance? Does anything read as a prediction about an individual? Is a person living with one of these conditions treated as ordinary?",
  dying:
    "Are the real pages named first and plainly? Is the practical material practical? Is there anything here that a recently bereaved person, or a person who is dying, would find careless?",
};

const sensitive = MILESTONES.filter((m) => m.sensitivity).sort((a, b) =>
  (a.sensitivity + a.id).localeCompare(b.sensitivity + b.id),
);

const out = [];
const w = (s = "") => out.push(s);

w("# Sensitive-record review pack — TGTL 5.0 timeline");
w();
w("GENERATED by `tools/timeline-sensitive-review.mjs`. Do not edit by hand; re-run it.");
w();
w("This is the document the launch-gate reviewers read (blueprint §5.3, §5.9). It contains every");
w("record on the timeline flagged sensitive, in full, with the exact source sentence behind every");
w("figure, and the question each reviewer is being asked.");
w();
w("**None of this has been reviewed yet. That is the gate.** The build ships behind it.");
w();
w("## What the build already does, so reviewers can judge what is left");
w();
w("Enforced structurally, not by intention — each is checked by gate T-6 and by the content compiler:");
w();
w("- Every record below renders in **plain language in both editions**. The game vocabulary is");
w("  withdrawn entirely on sensitive material; there is no unlock, gate, reward or chrome of any kind.");
w("- Every record carries a **care note** and a link to the **real page**.");
w("- Records flagged `dying` name `/situations/a-death` **and** `/situations/grief`, both, first.");
w("- Child-development records automatically render two standing lines:");
w(`  - “${SCREENING_LINE}”`);
w(`  - “${VARIATION_LINE}”`);
w("- **No rate renders on any surface**; figures live in the evidence drawer beside their source.");
w("- **No death marker on the spine, no per-year mortality figure**, and life expectancy renders");
w("  once, in the later-life stage intro, excluded from the spine and from every year card.");
w("- **Crisis-tier material appears nowhere on the timeline.**");
w();
w("What a lint cannot check, and what the review is actually for, is TONE — whether any of this");
w("reads as a verdict to the person most likely to be hurt by it.");
w();
w("---");
w();

const bySens = {};
for (const m of sensitive) (bySens[m.sensitivity] ??= []).push(m);

for (const [sens, rows] of Object.entries(bySens)) {
  w(`## \`${sens}\` — ${rows.length} record${rows.length === 1 ? "" : "s"} · ${REVIEWER[sens]} REVIEW`);
  w();
  w(`**The question for this reviewer:** ${ASK[sens]}`);
  w();
  for (const m of rows) {
    w(`### \`${m.id}\` — ${m.label}`);
    w();
    w(`- **Lane:** ${LANE_LABEL[m.lane]} · **Kind:** ${KIND_LABEL[m.kind]}${m.optional ? " · optional" : ""}`);
    w(`- **Renders as:** ${m.researchRequired ? "*not yet sourced* (no figure shown)" : `\`${windowText(m)}\``}`);
    if (m.renderAs === "stage-intro-note") {
      w(`- **Placement:** in the *${STAGES_TL.find((s) => s.id === m.stageId)?.label ?? m.stageId}* stage intro only — deliberately NOT on the spine and NOT in any year card (§5.4).`);
    }
    if (m.population) w(`- **Population:** ${m.population}`);
    w(`- **Care note:** “${m.careNote}”`);
    w(`- **Routes:** ${[m.readRef, ...(m.alsoRead ?? [])].join(" · ")}`);
    if (m.whatChanges?.length) {
      w(`- **What changes:**`);
      for (const c of m.whatChanges) w(`    - ${c}`);
    }
    if (m.notes) w(`- **Authoring note:** ${m.notes}`);
    if (m.analysis) {
      w(`- **Timing analysis** (this is where tone risk is highest):`);
      for (const [k, b] of Object.entries(m.analysis)) {
        if (!b) continue;
        w(`    - **${k}** — ${b.tends}`);
        for (const c of b.costs ?? []) w(`        - cost: ${c}`);
        for (const r of b.routes ?? []) w(`        - route: ${r}`);
      }
    }
    const srcs = m.sources ?? [];
    if (srcs.length) {
      w(`- **The sentences the figures came from:**`);
      for (const sid of srcs) {
        const s = SOURCES[sid];
        if (!s) continue;
        w(`    - “${s.excerpt}”`);
        w(`      — ${s.publisher}, ${s.url} (data ${s.dataYear}, published ${s.publicationYear}, checked ${s.retrievedOn})`);
        w(`      — what it measured: ${s.measures}`);
      }
    }
    if (m.researchRequired) {
      w(`- **Not yet sourced.** ${m.researchNote}`);
    }
    w();
  }
  w("---");
  w();
}

w("## The stage intros a reviewer should also read");
w();
w("Two stage intros carry material in this territory and are prose rather than records:");
w();
for (const s of STAGES_TL) {
  if (s.id !== "stage-later" && s.id !== "dying-and-closure" && !s.rendersCrisisNote) continue;
  w(`### \`${s.id}\` — ${s.label}`);
  if (s.rendersCrisisNote) {
    w();
    w("Renders the standing crisis note (one sentence, a `/threshold` link, and the 988 line). That");
    w("note is a shared component, not authored here, and it is the ONLY reference to crisis material");
    w("anywhere on the timeline.");
  }
  if (s.sensitivity === "dying") {
    w();
    w("This is the terminal card. It names `/situations/a-death` and `/situations/grief` before");
    w("anything else.");
  }
  w();
  for (const p of s.intro) w(`> ${p}`);
  w();
}

writeFileSync(join(ROOT, "records/sensitive-review.md"), out.join("\n"));
console.log(
  `wrote records/sensitive-review.md — ${sensitive.length} sensitive records ` +
    `(${Object.entries(bySens).map(([k, v]) => `${k}:${v.length}`).join(", ")})`,
);
