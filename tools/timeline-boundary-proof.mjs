/**
 * The boundary proof (5.0 blueprint §0.2).
 *
 * Everything outside `tgtl-claude-5.0/` is read-only. This walks every sibling in
 * the workspace and every document at its root and reports anything modified since
 * this build began, with a content hash where something WAS touched — because a
 * boundary claim that quietly omits the one file you touched is not a proof.
 *
 * Usage: node --experimental-strip-types tools/timeline-boundary-proof.mjs
 */
import { readdirSync, statSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, dirname, relative, basename } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WORKSPACE = join(ROOT, "..");
// The build folder is whatever this repository is called on disk (it shipped as
// `tgtl-claude-5.0/` and was renamed `The Guidebook To Life Website/` on 2026-09-04
// after publishing); deriving it keeps the proof honest across renames.
const BUILD_DIR = basename(ROOT);

/**
 * This build's FIRST WRITE: the robocopy that created tgtl-claude-5.0/, at
 * 2026-09-03 22:53:15 local. Anything outside the build folder newer than this
 * needs explaining.
 *
 * Deliberately not set earlier. `blueprint_TGTL_5.0.md` carries mtime 22:47:53 —
 * the architect's own final write, six minutes before this build touched anything,
 * and already present in the first directory listing this session took. An earlier
 * cut-off flags it as modified, which is false; the executor only ever read it.
 */
const BUILD_START = new Date("2026-09-03T22:53:15");
/** 4.0's own last write, from its build (§0.2 sequencing fact). */
const FORTY_BOUNDARY = new Date("2026-08-27T19:35:52");

const SKIP_DIRS = new Set(["node_modules", ".next", "out", ".git"]);

function walk(dir, acc = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return acc;
  }
  for (const e of entries) {
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      walk(join(dir, e.name), acc);
    } else {
      acc.push(join(dir, e.name));
    }
  }
  return acc;
}

const sha = (f) => createHash("sha256").update(readFileSync(f)).digest("hex");

const siblings = readdirSync(WORKSPACE, { withFileTypes: true })
  .filter((e) => e.isDirectory() && e.name !== BUILD_DIR && !SKIP_DIRS.has(e.name))
  .map((e) => e.name);

const rootDocs = readdirSync(WORKSPACE, { withFileTypes: true })
  .filter((e) => e.isFile())
  .map((e) => join(WORKSPACE, e.name));

const out = [];
const w = (s = "") => out.push(s);

w("# records/boundary-proof.md — TGTL 5.0");
w();
w("GENERATED by `tools/timeline-boundary-proof.mjs`.");
w();
w("Blueprint §0.2: everything outside `tgtl-claude-5.0/` is read-only. This is the check,");
w("run over every sibling folder and every document at the workspace root.");
w();
w(`Build folder: \`${BUILD_DIR}\``);
w(`Build began: ${BUILD_START.toISOString()}`);
w();
w("---");
w();

let touched = 0;
w("## Sibling folders");
w();
for (const s of siblings) {
  const files = walk(join(WORKSPACE, s));
  const newer = files.filter((f) => statSync(f).mtime > BUILD_START);
  if (newer.length === 0) {
    w(`- \`${s}/\` — ${files.length} files, **none modified since this build began**.`);
  } else {
    touched += newer.length;
    w(`- \`${s}/\` — ${files.length} files, **${newer.length} MODIFIED**:`);
    for (const f of newer) {
      const rel = relative(WORKSPACE, f).split("\\").join("/");
      w(`    - \`${rel}\``);
      w(`      - mtime: ${statSync(f).mtime.toISOString()}`);
      w(`      - sha256: \`${sha(f)}\``);
    }
  }
}
w();

w("## Workspace root documents");
w();
w("Note on the cut-off: `blueprint_TGTL_5.0.md` carries mtime 2026-09-03 22:47:53 local — the");
w("architect's own final write, six minutes before this build's first write, and already present");
w("in the first directory listing this session took. It is read-only input and was only ever read.");
w();
w("**Three root documents carry a later mtime, and none was written by this build.** After the");
w("build handed back, the architect ran the acceptance review and wrote two files at the workspace");
w("root: the errata section appended to `blueprint_TGTL_5.0.md` (section thirteen), and the fix");
w("handoff `TGTL_5.0_FIX_HANDOFF_PROMPT.md`. The fix pass then read both and wrote neither. The");
w("third, `TGTL_5.0_MVP_AUDIT_HANDOFF_PROMPT.md`, is the owner's handoff for the MVP audit and the");
w("publish pass (2026-09-04); the audit session read it and wrote nothing outside this folder. They");
w("are listed below because a boundary proof that filters out the files it does not want to explain");
w("is not a proof; the claim being made is that nothing outside the build folder was written BY");
w("this build, not that nothing outside it ever changed.");
w();
const newerDocs = rootDocs.filter((f) => statSync(f).mtime > BUILD_START);
if (newerDocs.length === 0) {
  w(`- ${rootDocs.length} documents, **none modified since this build began**.`);
} else {
  for (const f of newerDocs) {
    touched++;
    w(`- **MODIFIED** \`${relative(WORKSPACE, f)}\` — mtime ${statSync(f).mtime.toISOString()}, sha256 \`${sha(f)}\``);
  }
}
w();

w("## The 4.0 sequencing fact, re-checked");
w();
const fortyFiles = walk(join(WORKSPACE, "tgtl-claude-4.0"));
const fortyNewer = fortyFiles.filter((f) => statSync(f).mtime > FORTY_BOUNDARY);
w(`§0.2 records that no file in \`tgtl-claude-4.0/\` had been written since 2026-08-27 19:35:51.`);
w(`That was re-checked before copying and held: the newest files were its own`);
w(`\`KNOWN_LIMITATIONS.md\` and \`DECISIONS.md\`, the 4.0 build's final writes.`);
w();
if (fortyNewer.length === 0) {
  w("Nothing in 4.0 is newer than that boundary now either.");
} else {
  w(`**${fortyNewer.length} file(s) in 4.0 now carry a later mtime.** Each is accounted for below.`);
  w();
  for (const f of fortyNewer) {
    const rel = relative(WORKSPACE, f).split("\\").join("/");
    const twin = join(ROOT, relative(join(WORKSPACE, "tgtl-claude-4.0"), f));
    w(`- \`${rel}\``);
    w(`    - mtime: ${statSync(f).mtime.toISOString()}`);
    w(`    - sha256: \`${sha(f)}\``);
    if (existsSync(twin)) {
      const same = sha(twin) === sha(f);
      w(`    - the 5.0 copy of the same file: \`${sha(twin)}\``);
      w(`    - **content ${same ? "IDENTICAL — only the mtime moved" : "DIFFERS"}**`);
    }
  }
}
w();
w("### Why one 4.0 file has a later mtime, stated rather than omitted");
w();
w("The 4.0 `tests/falsify-walls.sh` hardcodes `cd \"F:/.../tgtl-claude-4.0\"`, so it operates on");
w("the 4.0 folder no matter which tree it ships in. Run once from the 5.0 copy before that was");
w("noticed, it planted a violation into `content/sim/campaign/actions/batch-people.ts` in **4.0**,");
w("then restored it. The restore is verified above by hash: the content is byte-identical to the");
w("pristine copy taken before any script ran. Only the modification time moved.");
w();
w("The 5.0 copy of that script is fixed to locate its own repo root, and that fix should port");
w("back to 4.0 — it is a live trap for anyone who copies that folder again.");
w();
w("---");
w();
w(`**Result: ${touched === 0 ? "nothing outside the build folder was modified." : `${touched} file(s) outside the build folder carry a later mtime; each is listed above with its hash.`}**`);
w();

writeFileSync(join(ROOT, "records/boundary-proof.md"), out.join("\n"));
console.log(`wrote records/boundary-proof.md — ${siblings.length} sibling folders, ${rootDocs.length} root documents, ${touched} touched`);
