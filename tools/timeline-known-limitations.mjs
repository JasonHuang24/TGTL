/**
 * Regenerates the research-required section of KNOWN_LIMITATIONS.md from the
 * compiled timeline content (5.0 blueprint §4.6, T-13).
 *
 * T-13 asserts that the count of `researchRequired` records in content equals the
 * count in KNOWN_LIMITATIONS.md and that every such record is listed there. Two
 * hand-maintained lists drift; one generated list cannot. The generator writes
 * between two markers and leaves the rest of the file alone.
 *
 * Usage: node --experimental-strip-types tools/timeline-known-limitations.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { MILESTONES } from "../content/timeline/generated/index.ts";
import { LANE_LABEL, KIND_LABEL } from "../content/timeline/schema.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FILE = join(ROOT, "KNOWN_LIMITATIONS.md");

const START = "<!-- TIMELINE-RESEARCH-REQUIRED:START (generated by tools/timeline-known-limitations.mjs) -->";
const END = "<!-- TIMELINE-RESEARCH-REQUIRED:END -->";

const rr = MILESTONES.filter((m) => m.researchRequired === true).sort((a, b) => a.id.localeCompare(b.id));

const lines = [];
lines.push(START);
lines.push("");
lines.push(`**research-required records: ${rr.length}**`);
lines.push("");
if (rr.length === 0) {
  lines.push("Every record on the timeline that shows an age carries a source we fetched and quoted.");
} else {
  lines.push(
    "Each of these is a claim whose SHAPE we are confident about and whose NUMBER we do not have. " +
      "They render on the timeline with the calm label “not yet sourced”, they show no digit, and they " +
      "are the honest alternative to guessing. Each line gives the query that would resolve it.",
  );
  lines.push("");
  for (const m of rr) {
    lines.push(`- **\`${m.id}\`** — ${m.label}`);
    lines.push(`  - lane: ${LANE_LABEL[m.lane]} · kind: ${KIND_LABEL[m.kind]}`);
    if (m.windowInWords) lines.push(`  - what we can say without a number: “${m.windowInWords}”`);
    lines.push(`  - **query that would resolve it:** ${m.researchNote}`);
  }
}
lines.push("");
lines.push(END);

const src = readFileSync(FILE, "utf8");
const a = src.indexOf(START);
const b = src.indexOf(END);
let next;
if (a === -1 || b === -1) {
  console.error(
    `markers not found in KNOWN_LIMITATIONS.md — add\n${START}\n${END}\nwhere the list should go.`,
  );
  process.exit(1);
} else {
  next = src.slice(0, a) + lines.join("\n") + src.slice(b + END.length);
}
writeFileSync(FILE, next);
console.log(`wrote ${rr.length} research-required record(s) into KNOWN_LIMITATIONS.md`);
