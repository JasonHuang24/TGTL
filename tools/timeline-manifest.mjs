/**
 * A compact, human-readable manifest of the compiled pool.
 * Written so a later authoring pass can see exactly which records exist, what each
 * one is, and which are sensitive — without reading 6,000 lines of generated JSON.
 * Usage: node --experimental-strip-types tools/timeline-manifest.mjs
 */
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { MILESTONES } from "../content/timeline/generated/index.ts";
import { LANE_LABEL, LANES } from "../content/timeline/schema.ts";
import { windowText } from "../content/timeline/select.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = ["# Timeline pool manifest (generated by tools/timeline-manifest.mjs)", ""];
out.push(`${MILESTONES.length} milestones.`, "");
for (const lane of LANES) {
  const rows = MILESTONES.filter((m) => m.lane === lane);
  out.push(`## ${LANE_LABEL[lane]} (${rows.length})`, "");
  for (const m of rows.sort((a, b) => a.id.localeCompare(b.id))) {
    const rr = m.researchRequired === true;
    const sens = m.sensitivity ? ` [SENSITIVE: ${m.sensitivity}]` : "";
    const when = rr ? "not yet sourced" : windowText(m);
    out.push(`- \`${m.id}\` — **${m.label}** · ${m.kind} · ${when}${sens}${m.optional ? " · optional" : ""}`);
  }
  out.push("");
}
writeFileSync(join(ROOT, "records/timeline-manifest.md"), out.join("\n"));
console.log(`wrote records/timeline-manifest.md (${MILESTONES.length} records)`);
